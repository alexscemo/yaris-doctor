"""Generates domain/src/main/kotlin/com/yarisdoctor/domain/car/PidTable.kt from a vehicle PID sheet (NLP130_engine_PIDs.xlsx).

  python -I tools/pid_table.py path/to/NLP130_engine_PIDs.xlsx > domain/src/main/kotlin/com/yarisdoctor/domain/car/PidTable.kt

Standard library only. Signed fields are two's complement: every signed item in this sheet is (no sign-magnitude ones).
"""
import sys, zipfile, xml.etree.ElementTree as ET

M = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'

# First match wins; enums that match nothing are switches, other values are engine
CATEGORIES = [
    ('Diagnostics', ['DTC', 'MIL', 'Codes', 'Learn', 'Lrn', 'Warmup', 'Run Time', 'IG-ON', 'Start Time', 'Glow Request', 'History', 'Initial']),
    ('DPF / exhaust', ['PM Accumulation', 'DPNR', 'DPF', 'Exhaust', 'AF Lambda', 'AF Sensor', 'AFS']),
    ('EGR', ['EGR']),
    ('Turbo', ['VN ', 'Boost', 'MAP']),
    ('Fuel / injection', ['Injection', 'Fuel', 'SCV', 'Rail']),
    ('Air intake', ['MAF', 'Intake', 'Throttle', 'Atmosphere']),
    ('Electrical', ['Battery', 'Alternate', 'Electrical', 'Fan']),
]


def sheets(path):
    z = zipfile.ZipFile(path)
    names = [s.get('name') for s in ET.fromstring(z.read('xl/workbook.xml')).find(M + 'sheets')]
    out = {}
    for i, name in enumerate(names, 1):
        rows = []
        for row in ET.fromstring(z.read(f'xl/worksheets/sheet{i}.xml')).iter(M + 'row'):
            cells = []
            for c in row.findall(M + 'c'):
                v = c.find(M + 'v')
                cells.append(''.join(t.text or '' for t in c.iter(M + 't')) if c.get('t') == 'inlineStr' else (v.text if v is not None else ''))
            rows.append(cells)
        out[name] = [dict(zip(rows[0], r)) for r in rows[1:]]
    return out


def category(name, kind):
    for cat, words in CATEGORIES:
        if any(w in name for w in words):
            return cat
    return 'Switches' if kind == 'enum' else 'Engine'


def kstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def num(s):
    return 'null' if s == '' else repr(float(s))


def main():
    s = sheets(sys.argv[1])
    enums = {}
    for e in s['Enums']:
        enums.setdefault(e['Parameter'], {})[int(e['Raw value'])] = e['Meaning']
    print('package com.yarisdoctor.domain.car\n')
    print('// GENERATED by tools/pid_table.py from NLP130_engine_PIDs.xlsx (vehicle capture, 2026-10-20). Do not edit by hand.\n')
    print('/** Every engine ECU live-data item of the NLP130 (1ND-TV), as the engine ECU reports it. */')
    print('val PIDS = listOf(')
    for p in s['PIDs']:
        lid = p['Request (hex)'].split()[1]
        e = enums.get(p['Parameter'])
        if e:
            assert sorted(e) == list(range(len(e))), p['Parameter']
        args = [
            kstr(p['Parameter']), kstr(p['Unit']), kstr(lid), p['Payload length (bytes)'], p['Bit start (MSB-first)'], p['Bit end'],
            'true' if p['Formula'].startswith('signed') else 'false', p['Mul'], p['Div'], p['Offset'], p['Decimals'],
            num(p['Range min']), num(p['Range max']),
            'listOf(' + ', '.join(kstr(e[k]) for k in sorted(e)) + ')' if e else 'null',
            kstr(category(p['Parameter'], p['Type'])),
        ]
        print(f'    Pid({", ".join(args)}),')
    print(')')
    print()
    print('/** Idle payload per lid from the same capture (engine warm-ish, ~41 °C): fixtures for tests and Debug mode. */')
    print('val PID_IDLE = mapOf(')
    for l in s['LIDs']:
        print(f'    {kstr(l["LID"])} to {kstr(l["Sample payload (hex, idle)"].replace(" ", ""))},')
    print(')')


if __name__ == '__main__':
    main()
